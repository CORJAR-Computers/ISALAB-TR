-- ============================================================================
-- ISALAB · Migración 0027 — Visitas y servicios de la visita (recepción)
--
-- VISITS es la columna vertebral de la recepción de pacientes: un paciente
-- llega, pide uno o varios servicios (VISIT_SERVICES) y se va atendido y
-- facturado, con el laboratorio como uno más de esos servicios. NO reemplaza
-- a SAMPLES (la trazabilidad de muestras no cambia): los módulos existentes
-- (CONSULTATIONS, SAMPLES, SURGERIES, VACCINES) ganan VISIT_ID opcional para
-- vincularse a la visita que los originó.
--
-- El precio de cada línea (UNIT_PRICE, TAX_RATE) se congela al agregar el
-- servicio: cambiar el catálogo (0025) nunca reescribe visitas ni facturas.
-- ============================================================================

CREATE TABLE VISITS (
    ID             D_PK NOT NULL PRIMARY KEY,
    -- Código V-YYYY-NNNN (trigger BI_VISITS).
    CODE           D_CODE NOT NULL UNIQUE,
    PATIENT_ID     D_PK NOT NULL REFERENCES PATIENTS (ID) ON DELETE CASCADE,
    OWNER_ID       D_PK NOT NULL REFERENCES OWNERS (ID),
    -- Cita que originó la visita (fase 3); NULL = walk-in.
    APPOINTMENT_ID D_PK,
    ARRIVED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIORITY       VARCHAR(12) CHARACTER SET UTF8 DEFAULT 'NORMAL' NOT NULL
                   CHECK (PRIORITY IN ('NORMAL', 'URGENTE')),
    -- EN_ESPERA | EN_ATENCION | FINALIZADA | FACTURADA | CANCELADA
    STATUS         VARCHAR(20) CHARACTER SET UTF8 DEFAULT 'EN_ESPERA' NOT NULL,
    NOTES          D_NOTES,
    CREATED_BY     D_PK REFERENCES USERS (ID) ON DELETE SET NULL,
    CREATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE GENERATOR GEN_VISITS_ID;

CREATE TABLE VISIT_SERVICES (
    ID              D_PK NOT NULL PRIMARY KEY,
    VISIT_ID        D_PK NOT NULL REFERENCES VISITS (ID) ON DELETE CASCADE,
    SERVICE_ID      D_PK NOT NULL REFERENCES SERVICES (ID),
    -- Profesional asignado (veterinario, peluquero…).
    PROFESSIONAL_ID D_PK REFERENCES USERS (ID) ON DELETE SET NULL,
    QUANTITY        INTEGER DEFAULT 1 NOT NULL CHECK (QUANTITY > 0),
    -- Snapshot del precio del catálogo al agregar la línea.
    UNIT_PRICE      D_AMOUNT NOT NULL,
    -- Snapshot del IVA del servicio (NULL = IVA global de la clínica).
    TAX_RATE        D_PERCENT,
    -- PENDIENTE | EN_PROCESO | COMPLETADA | CANCELADA
    STATUS          VARCHAR(20) CHARACTER SET UTF8 DEFAULT 'PENDIENTE' NOT NULL,
    STARTED_AT      TIMESTAMP,
    FINISHED_AT     TIMESTAMP,
    NOTES           D_NOTES,
    SEQ             INTEGER DEFAULT 0 NOT NULL,
    CREATED_AT      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE GENERATOR GEN_VISIT_SERVICES_ID;

CREATE INDEX IX_VISITS_STATUS_ARRIVED ON VISITS (STATUS, ARRIVED_AT);
CREATE INDEX IX_VISITS_PATIENT ON VISITS (PATIENT_ID);
CREATE INDEX IX_VISITS_OWNER ON VISITS (OWNER_ID);
CREATE INDEX IX_VISIT_SERVICES_VISIT ON VISIT_SERVICES (VISIT_ID);
CREATE INDEX IX_VISIT_SERVICES_SERVICE ON VISIT_SERVICES (SERVICE_ID, STATUS);

-- ================= VÍNCULOS OPCIONALES CON MÓDULOS EXISTENTES ===============

ALTER TABLE CONSULTATIONS ADD VISIT_ID D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;
ALTER TABLE SAMPLES      ADD VISIT_ID D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;
ALTER TABLE SURGERIES    ADD VISIT_ID D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;
ALTER TABLE VACCINES     ADD VISIT_ID D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;

-- Factura ligada a la visita (cobro en un clic; 1 factura por visita se
-- valida en Rust, Firebird no permite UNIQUE parcial con condición).
ALTER TABLE INVOICES ADD VISIT_ID D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;

-- Rastreo de la línea de factura: de qué visita/registro proviene.
ALTER TABLE INVOICE_ITEMS ADD VISIT_ID       D_PK REFERENCES VISITS (ID) ON DELETE SET NULL;
ALTER TABLE INVOICE_ITEMS ADD CONSULTATION_ID D_PK REFERENCES CONSULTATIONS (ID) ON DELETE SET NULL;
ALTER TABLE INVOICE_ITEMS ADD SURGERY_ID      D_PK REFERENCES SURGERIES (ID) ON DELETE SET NULL;
ALTER TABLE INVOICE_ITEMS ADD VACCINE_ID      D_PK REFERENCES VACCINES (ID) ON DELETE SET NULL;

CREATE INDEX IX_INVOICE_ITEMS_VISIT ON INVOICE_ITEMS (VISIT_ID);
CREATE INDEX IX_INVOICES_VISIT ON INVOICES (VISIT_ID);

SET TERM ^ ;

CREATE TRIGGER BI_VISITS FOR VISITS BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_VISITS_ID, 1);
    IF (NEW.CODE IS NULL) THEN
        NEW.CODE = 'V-' || EXTRACT(YEAR FROM NEW.ARRIVED_AT) || '-' ||
                   LPAD(NEW.ID, 4, '0');
END^

CREATE TRIGGER BI_VISIT_SERVICES FOR VISIT_SERVICES BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_VISIT_SERVICES_ID, 1);
END^

SET TERM ; ^
