-- Adjuntos (fotos de placas, frotis, electroforesis) por resultado de laboratorio.
-- El archivo se copia a la carpeta de datos de la app (app_data/attachments) y
-- aquí solo se guarda su ruta persistida + metadatos para trazabilidad.
CREATE TABLE RESULT_ATTACHMENTS (
    ID         INTEGER NOT NULL PRIMARY KEY,
    RESULT_ID  INTEGER NOT NULL REFERENCES LAB_RESULTS (ID) ON DELETE CASCADE,
    FILE_NAME  VARCHAR(255) CHARACTER SET UTF8 NOT NULL,
    FILE_PATH  VARCHAR(1000) CHARACTER SET UTF8 NOT NULL,
    MIME_TYPE  VARCHAR(100) CHARACTER SET UTF8,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE GENERATOR GEN_RESULT_ATTACHMENTS_SEQ;

SET TERM ^ ;
CREATE TRIGGER TR_RESULT_ATTACHMENTS_BI FOR RESULT_ATTACHMENTS ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
    IF (NEW.ID IS NULL) THEN
        NEW.ID = GEN_ID(GEN_RESULT_ATTACHMENTS_SEQ, 1);
END^
SET TERM ; ^
