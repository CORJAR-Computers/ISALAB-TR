-- ============================================================================
-- ISALAB · Migración 0036 — Pagos, abonos y caja (fase 7)
--
-- Una factura puede cobrarse en varias recepciones (abonos) y cada recepción
-- puede combinar varios métodos de pago. El saldo de la factura se deriva de
-- PAYMENT_ALLOCATIONS; no se guarda en INVOICES.
--
-- CASH_SESSIONS representa la caja física abierta. Solo puede existir una
-- ABIERTA: el índice único sobre OPEN_KEY (1 o NULL) lo garantiza incluso con
-- varias PCs escribiendo a la vez.
--
-- Backfill: las facturas PAGADA anteriores no tienen recepción; se migran a un
-- pago LEG-<número> para que los reportes de cobros sean consistentes. El
-- arqueo histórico no se reconstruye.
-- ============================================================================

CREATE TABLE PAYMENT_METHODS (
    CODE               VARCHAR(30) CHARACTER SET UTF8 NOT NULL PRIMARY KEY,
    NAME               VARCHAR(60) CHARACTER SET UTF8 NOT NULL,
    -- EFECTIVO | ELECTRONICO | OTRO (define qué entra al arqueo)
    KIND               VARCHAR(16) CHARACTER SET UTF8 DEFAULT 'OTRO' NOT NULL
                       CHECK (KIND IN ('EFECTIVO', 'ELECTRONICO', 'OTRO')),
    REQUIRES_REFERENCE BOOLEAN DEFAULT FALSE NOT NULL,
    ACTIVE             BOOLEAN DEFAULT TRUE NOT NULL,
    SORT_ORDER         INTEGER DEFAULT 0 NOT NULL
);

