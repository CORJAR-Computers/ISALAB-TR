CREATE TRIGGER BI_CASH_SESSIONS FOR CASH_SESSIONS BEFORE INSERT OR UPDATE AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_CASH_SESSIONS_ID, 1);
    IF (NEW.CODE IS NULL OR NEW.CODE = '') THEN
        NEW.CODE = 'CAJ-' || LPAD(NEW.ID, 8, '0');
    IF (NEW.STATUS = 'ABIERTA') THEN
        NEW.OPEN_SLOT = 1;
    ELSE
        NEW.OPEN_SLOT = NULL;
END^

CREATE TRIGGER BI_PAYMENTS FOR PAYMENTS BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_PAYMENTS_ID, 1);
    IF (NEW.CODE IS NULL OR NEW.CODE = '') THEN
        NEW.CODE = 'REC-' || LPAD(NEW.ID, 6, '0');
END^

CREATE TRIGGER BI_PAYMENT_LINES FOR PAYMENT_LINES BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_PAYMENT_LINES_ID, 1);
END^

CREATE TRIGGER BI_PAYMENT_ALLOCATIONS FOR PAYMENT_ALLOCATIONS BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_PAYMENT_ALLOCATIONS_ID, 1);
END^

CREATE TRIGGER BI_CASH_MOVEMENTS FOR CASH_MOVEMENTS BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_CASH_MOVEMENTS_ID, 1);
END^

CREATE TRIGGER BI_CASH_COUNT_LINES FOR CASH_COUNT_LINES BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_CASH_COUNT_LINES_ID, 1);
END^

CREATE TRIGGER BI_CASH_SESSION_TOTALS FOR CASH_SESSION_TOTALS BEFORE INSERT AS
BEGIN
    IF (NEW.ID IS NULL) THEN NEW.ID = GEN_ID(GEN_CASH_SESSION_TOTALS_ID, 1);
END^

SET TERM ; ^

-- Backfill de facturas ya pagadas: una recepción histórica por factura, con
-- una línea del método original (o OTRO si el texto no está en el catálogo).
INSERT INTO PAYMENTS (ID, CODE, OWNER_ID, PATIENT_ID, RECEIVED_AT, TOTAL, STATUS, NOTES)
SELECT GEN_ID(GEN_PAYMENTS_ID, 1), 'LEG-' || i.INVOICE_NUMBER,
       i.OWNER_ID, i.PATIENT_ID, i.ISSUE_DATE, i.TOTAL, 'APLICADO',
       'Migrado desde facturación anterior'
FROM INVOICES i
WHERE i.STATUS = 'PAGADA' AND i.TOTAL > 0
  AND NOT EXISTS (
      SELECT 1 FROM PAYMENTS p WHERE p.CODE = 'LEG-' || i.INVOICE_NUMBER
  );

INSERT INTO PAYMENT_LINES (ID, PAYMENT_ID, METHOD_CODE, AMOUNT)
SELECT GEN_ID(GEN_PAYMENT_LINES_ID, 1), p.ID,
       CASE WHEN EXISTS (
                SELECT 1 FROM PAYMENT_METHODS m WHERE m.CODE = i.PAYMENT_METHOD
            )
            THEN i.PAYMENT_METHOD
            ELSE 'OTRO'
       END,
       i.TOTAL
FROM PAYMENTS p
JOIN INVOICES i ON p.CODE = 'LEG-' || i.INVOICE_NUMBER
WHERE NOT EXISTS (
    SELECT 1 FROM PAYMENT_LINES l WHERE l.PAYMENT_ID = p.ID
);

INSERT INTO PAYMENT_ALLOCATIONS (ID, PAYMENT_ID, INVOICE_ID, AMOUNT)
SELECT GEN_ID(GEN_PAYMENT_ALLOCATIONS_ID, 1), p.ID, i.ID, i.TOTAL
FROM PAYMENTS p
JOIN INVOICES i ON p.CODE = 'LEG-' || i.INVOICE_NUMBER
WHERE NOT EXISTS (
    SELECT 1 FROM PAYMENT_ALLOCATIONS a
    WHERE a.PAYMENT_ID = p.ID AND a.INVOICE_ID = i.ID
);
