-- Ejecutada desde Rust al primer arranque (src-tauri/src/db/migrations.rs).
-- Convenciones:
--   * IDs por GENERATOR + trigger BEFORE INSERT (IF NEW.ID IS NULL).
--   * DSQL parametrizado en la app; aquí SOLO DDL/DML estructurado.
--   * DOMAINs para tipos reutilizables (documentos, teléfono, textos, etc.).
--   * EVENT_LOG + POST_EVENT para notificar al frontend cambios de muestras.
