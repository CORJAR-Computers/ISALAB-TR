-- ============ TRIGGERS DE EVENTOS (Firebird Events → frontend) ==============
-- Se notifica al frontend cuando cambia el estado de una muestra o se cargan
-- resultados, garantizando trazabilidad en tiempo real.

CREATE TRIGGER AI_SAMPLES FOR SAMPLES AFTER INSERT OR UPDATE AS
BEGIN
    INSERT INTO EVENT_LOG (EVENT_NAME, REF_ID, PATIENT_ID, STATUS)
    VALUES ('SAMPLE_CHANGED', NEW.ID, NEW.PATIENT_ID, NEW.STATUS);
    POST_EVENT 'SAMPLE_CHANGED';
END^

CREATE TRIGGER AI_LAB_RESULTS FOR LAB_RESULTS AFTER INSERT OR UPDATE AS
BEGIN
    INSERT INTO EVENT_LOG (EVENT_NAME, REF_ID, PATIENT_ID, STATUS)
    VALUES ('LAB_RESULT_CHANGED',
            NEW.SAMPLE_ID,
            (SELECT FIRST 1 PATIENT_ID FROM SAMPLES WHERE ID = NEW.SAMPLE_ID),
            NEW.STATUS);
    POST_EVENT 'LAB_RESULT_CHANGED';
END^

-- ==================== STORED PROCEDURES (LÓGICA CLÍNICA) ====================
-- Encuentra el valor de referencia más específico para
-- (analito, especie, sexo, edad). Prioriza rango con sexo exacto.
CREATE PROCEDURE SP_FIND_REFERENCE_RANGE (
    P_ANALYTE_ID  INTEGER,
    P_SPECIES_ID  INTEGER,
    P_SEX         CHAR(1),
    P_AGE_MONTHS  INTEGER
) RETURNS (
    RR_ID         INTEGER,
    MIN_VALUE     DOUBLE PRECISION,
    MAX_VALUE     DOUBLE PRECISION,
    CRITICAL_MIN  DOUBLE PRECISION,
    CRITICAL_MAX  DOUBLE PRECISION
) AS
BEGIN
    SELECT FIRST 1 rr.ID, rr.MIN_VALUE, rr.MAX_VALUE, rr.CRITICAL_MIN, rr.CRITICAL_MAX
    FROM REFERENCE_RANGES rr
    WHERE rr.ANALYTE_ID = :P_ANALYTE_ID
      AND rr.SPECIES_ID = :P_SPECIES_ID
      AND :P_AGE_MONTHS BETWEEN rr.AGE_MIN_MONTHS AND rr.AGE_MAX_MONTHS
      AND (rr.SEX IS NULL OR rr.SEX = :P_SEX)
    ORDER BY CASE WHEN rr.SEX = :P_SEX THEN 0 ELSE 1 END,
             rr.AGE_MIN_MONTHS DESC
    INTO :RR_ID, :MIN_VALUE, :MAX_VALUE, :CRITICAL_MIN, :CRITICAL_MAX;
    SUSPEND;
END^

-- Valida un resultado analítico contra los rangos de referencia de la especie,
-- sexo y edad del paciente asociado a la muestra. Devuelve el estado clínico.
CREATE PROCEDURE SP_VALIDATE_ANALYTICAL_RESULT (
    P_SAMPLE_ID   INTEGER,
    P_ANALYTE_ID  INTEGER,
    P_VALUE       DOUBLE PRECISION
) RETURNS (
    RR_ID   INTEGER,
    STATUS  VARCHAR(10)
) AS
DECLARE VARIABLE V_SPECIES_ID  INTEGER;
DECLARE VARIABLE V_SEX         CHAR(1);
DECLARE VARIABLE V_AGE_MONTHS  INTEGER;
DECLARE VARIABLE V_MIN         DOUBLE PRECISION;
DECLARE VARIABLE V_MAX         DOUBLE PRECISION;
BEGIN
    SELECT FIRST 1 pa.SPECIES_ID, pa.SEX,
           COALESCE(CAST(DATEDIFF(MONTH, pa.BIRTH_DATE, CURRENT_TIMESTAMP) AS INTEGER), 0)
    FROM SAMPLES sa
    JOIN PATIENTS pa ON pa.ID = sa.PATIENT_ID
    WHERE sa.ID = :P_SAMPLE_ID
    INTO :V_SPECIES_ID, :V_SEX, :V_AGE_MONTHS;

    IF (:V_SPECIES_ID IS NULL) THEN
    BEGIN
        RR_ID  = NULL;
        STATUS = 'SIN_RANGO';
        SUSPEND;
        EXIT;
    END

    SELECT RR_ID, MIN_VALUE, MAX_VALUE
    FROM SP_FIND_REFERENCE_RANGE(:P_ANALYTE_ID, :V_SPECIES_ID, :V_SEX, :V_AGE_MONTHS)
    INTO :RR_ID, :V_MIN, :V_MAX;

    IF (:RR_ID IS NULL) THEN
    BEGIN
        STATUS = 'SIN_RANGO';
        SUSPEND;
        EXIT;
    END

    IF (:P_VALUE < :V_MIN) THEN
        STATUS = 'BAJO';
    ELSE IF (:P_VALUE > :V_MAX) THEN
        STATUS = 'ALTO';
    ELSE
        STATUS = 'NORMAL';

    SUSPEND;
END^

